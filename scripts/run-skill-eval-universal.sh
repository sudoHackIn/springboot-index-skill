#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'USAGE'
Universal skill eval runner.

Required:
  --skill-root PATH            Skill root directory (must contain SKILL.md)

Optional:
  --eval-dir PATH              Eval directory (default: <skill-root>/.eval)
  --index PATH                 Index JSON path (default: <eval-dir>/scenarios/indexes/*.json first)
  --cases-glob GLOB            Cases glob (default: <eval-dir>/scenarios/cases/*.json)
  --workdir PATH               Working directory for agent command (default: current dir)
  --date YYYY-MM-DD            Run date (default: today)
  --model NAME                 Model (default: gpt-5.4)
  --run-id ID                  Explicit run id (default autogenerated)
  --run-prefix PREFIX          Prefix for autogenerated run id (default: full)
  --rerun-failed-from DIR      Re-run only failed cases from existing run dir

Agent launch:
  --agent-bin BIN              Agent binary (default: codex)
  --agent-timeout-sec N        Per-case timeout seconds (default: 360)
  --agent-extra-arg ARG        Extra argument for agent command, repeatable
  --agent-extra-args STRING    Space-separated extra args (appended to --agent-extra-arg)

Assessment keys (from case JSON / output JSON):
  --case-id-key KEY            default: id
  --case-question-key KEY      default: question
  --expected-verdict-key KEY   default: expected_verdict
  --expected-regex-key KEY     default: expected_autoconfig_regex
  --actual-verdict-key KEY     default: verdict
  --actual-list-key KEY        default: matched_autoconfigs

Behavior flags:
  --allow-missing-json         Do not fail correctness when output json block is missing
  --debug                      Verbose logs
  -h, --help                   Show help

Output structure:
  <eval-dir>/runs/<date>/<model>/<run-id>/
USAGE
}

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || { echo "missing required command: $1" >&2; exit 1; }
}

now_date() {
  date +%F
}

ts() {
  date '+%Y-%m-%d %H:%M:%S'
}

sha256_of_file() {
  local file="$1"
  if [[ ! -f "$file" ]]; then
    echo ""
    return 0
  fi
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$file" | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$file" | awk '{print $1}'
  else
    echo ""
  fi
}

json_get_string() {
  local json="$1"
  local key="$2"
  jq -r --arg k "$key" '.[$k] // empty' <<<"$json"
}

json_get_array_csv() {
  local json="$1"
  local key="$2"
  jq -r --arg k "$key" '.[$k] // [] | if type=="array" then join(", ") else "" end' <<<"$json"
}

extract_last_json_block() {
  local file="$1"
  perl -0777 -ne 'while(/```json\s*(\{.*?\})\s*```/sg){$j=$1} END{print $j if defined $j}' "$file"
}

SKILL_ROOT=""
EVAL_DIR=""
INDEX_PATH=""
CASES_GLOB=""
WORKDIR="$(pwd)"
DATE="$(now_date)"
MODEL="gpt-5.4"
RUN_ID=""
RUN_PREFIX="full"
RUN_PREFIX_SET=false
RERUN_FAILED_FROM=""
AGENT_BIN="codex"
AGENT_TIMEOUT_SEC=360
DEBUG=false
ALLOW_MISSING_JSON=false

CASE_ID_KEY="id"
CASE_QUESTION_KEY="question"
EXPECTED_VERDICT_KEY="expected_verdict"
EXPECTED_REGEX_KEY="expected_autoconfig_regex"
ACTUAL_VERDICT_KEY="verdict"
ACTUAL_LIST_KEY="matched_autoconfigs"

AGENT_EXTRA_ARGS=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --skill-root) SKILL_ROOT="$2"; shift 2 ;;
    --eval-dir) EVAL_DIR="$2"; shift 2 ;;
    --index) INDEX_PATH="$2"; shift 2 ;;
    --cases-glob) CASES_GLOB="$2"; shift 2 ;;
    --workdir) WORKDIR="$2"; shift 2 ;;
    --date) DATE="$2"; shift 2 ;;
    --model) MODEL="$2"; shift 2 ;;
    --run-id) RUN_ID="$2"; shift 2 ;;
    --run-prefix) RUN_PREFIX="$2"; RUN_PREFIX_SET=true; shift 2 ;;
    --rerun-failed-from) RERUN_FAILED_FROM="$2"; shift 2 ;;
    --agent-bin) AGENT_BIN="$2"; shift 2 ;;
    --agent-timeout-sec) AGENT_TIMEOUT_SEC="$2"; shift 2 ;;
    --agent-extra-arg) AGENT_EXTRA_ARGS+=("$2"); shift 2 ;;
    --agent-extra-args)
      tmp_extra=()
      # Split by shell IFS; intended for simple arg bundles like "--sandbox workspace-write".
      read -r -a tmp_extra <<< "$2"
      AGENT_EXTRA_ARGS+=("${tmp_extra[@]}")
      shift 2
      ;;
    --case-id-key) CASE_ID_KEY="$2"; shift 2 ;;
    --case-question-key) CASE_QUESTION_KEY="$2"; shift 2 ;;
    --expected-verdict-key) EXPECTED_VERDICT_KEY="$2"; shift 2 ;;
    --expected-regex-key) EXPECTED_REGEX_KEY="$2"; shift 2 ;;
    --actual-verdict-key) ACTUAL_VERDICT_KEY="$2"; shift 2 ;;
    --actual-list-key) ACTUAL_LIST_KEY="$2"; shift 2 ;;
    --allow-missing-json) ALLOW_MISSING_JSON=true; shift ;;
    --debug) DEBUG=true; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown arg: $1" >&2; usage; exit 2 ;;
  esac
done

require_cmd jq
require_cmd perl
require_cmd "$AGENT_BIN"

[[ -n "$SKILL_ROOT" ]] || { echo "--skill-root is required" >&2; exit 2; }
[[ -f "$SKILL_ROOT/SKILL.md" ]] || { echo "SKILL.md not found under skill root: $SKILL_ROOT" >&2; exit 2; }

if [[ -z "$EVAL_DIR" ]]; then
  EVAL_DIR="$SKILL_ROOT/.eval"
fi

if [[ -z "$INDEX_PATH" ]]; then
  first_index=$(find "$EVAL_DIR/scenarios/indexes" -maxdepth 1 -type f -name '*.json' | sort | head -n 1 || true)
  [[ -n "$first_index" ]] || { echo "cannot auto-detect index json under $EVAL_DIR/scenarios/indexes" >&2; exit 2; }
  INDEX_PATH="$first_index"
fi

if [[ -z "$CASES_GLOB" ]]; then
  CASES_GLOB="$EVAL_DIR/scenarios/cases/*.json"
fi

if [[ -n "$RERUN_FAILED_FROM" && "$RUN_PREFIX_SET" == "false" ]]; then
  RUN_PREFIX="rerun-failed"
fi

if [[ -z "$RUN_ID" ]]; then
  if [[ -n "$RERUN_FAILED_FROM" ]]; then
    source_base=$(basename "$RERUN_FAILED_FROM")
    RUN_ID="${RUN_PREFIX}__${source_base}__$(date +%H%M%S)"
  else
    index_base=$(basename "$INDEX_PATH" .json)
    RUN_ID="${RUN_PREFIX}__${index_base}__all-cases__$(date +%H%M%S)"
  fi
fi

RUN_DIR="$EVAL_DIR/runs/$DATE/$MODEL/$RUN_ID"
mkdir -p "$RUN_DIR/cases"
RUN_LOG="$RUN_DIR/run.log"
: > "$RUN_LOG"

SKILL_MD_PATH="$SKILL_ROOT/SKILL.md"
SKILL_MD_SHA256="$(sha256_of_file "$SKILL_MD_PATH")"
INDEX_SHA256="$(sha256_of_file "$INDEX_PATH")"
SKILL_DECLARED_VERSION="$(
  perl -ne '
    if (/skill_version:\s*([A-Za-z0-9._-]+)/) { print $1; exit 0 }
    if (/`skill_version:\s*([A-Za-z0-9._-]+)`/) { print $1; exit 0 }
  ' "$SKILL_MD_PATH" 2>/dev/null || true
)"

GIT_COMMIT=""
GIT_BRANCH=""
GIT_DIRTY=false
if git -C "$WORKDIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  GIT_COMMIT="$(git -C "$WORKDIR" rev-parse HEAD 2>/dev/null || true)"
  GIT_BRANCH="$(git -C "$WORKDIR" rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
  if ! git -C "$WORKDIR" diff --quiet --ignore-submodules -- 2>/dev/null || ! git -C "$WORKDIR" diff --cached --quiet --ignore-submodules -- 2>/dev/null; then
    GIT_DIRTY=true
  fi
fi

log() {
  local msg="$1"
  printf '[%s] %s\n' "$(ts)" "$msg" | tee -a "$RUN_LOG"
}

$DEBUG && log "debug=on"
log "run_start run_id=$RUN_ID model=$MODEL date=$DATE"
log "skill_root=$SKILL_ROOT"
log "eval_dir=$EVAL_DIR"
log "index=$INDEX_PATH"
log "cases_glob=$CASES_GLOB"
log "skill_md_sha256=${SKILL_MD_SHA256:-unknown}"
log "skill_declared_version=${SKILL_DECLARED_VERSION:-unknown}"
log "index_sha256=${INDEX_SHA256:-unknown}"
if [[ -n "$RERUN_FAILED_FROM" ]]; then
  log "mode=rerun_failed_only"
  log "source_run=$RERUN_FAILED_FROM"
fi

summary_jsonl="$RUN_DIR/.summary_cases.jsonl"
: > "$summary_jsonl"

total=0
passed=0
failed=0

if [[ -n "$RERUN_FAILED_FROM" ]]; then
  [[ -d "$RERUN_FAILED_FROM/cases" ]] || { echo "invalid --rerun-failed-from (missing cases dir): $RERUN_FAILED_FROM" >&2; exit 2; }

  rerun_manifest="$RUN_DIR/.rerun_manifest.tsv"
  : > "$rerun_manifest"
  find "$RERUN_FAILED_FROM/cases" -name assessment.json -print0 \
    | xargs -0 jq -r '
        select(.pass!=true)
        | [(.source_case_file // "unknown"), .id, (.expected.verdict // .expected_verdict // ""), (.expected.regex // .expected.autoconfig_regex // .expected_autoconfig_regex // "")]
        | @tsv
      ' \
    | sort > "$rerun_manifest"

  if [[ ! -s "$rerun_manifest" ]]; then
    log "no_failed_cases_in_source_run"
  fi

  while IFS=$'\t' read -r rel_file id expected_verdict expected_regex; do
    [[ -n "${id:-}" ]] || continue

    old_prompt="$RERUN_FAILED_FROM/cases/$id/prompt.txt"
    if [[ ! -f "$old_prompt" ]]; then
      log "skip_missing_prompt case=$id scenario=${rel_file:-unknown}"
      continue
    fi

    case_dir="$RUN_DIR/cases/$id"
    mkdir -p "$case_dir"

    prompt_file="$case_dir/prompt.txt"
    output_file="$case_dir/output.md"
    events_file="$case_dir/events.jsonl"
    stderr_file="$case_dir/stderr.log"
    commands_file="$case_dir/commands.log"
    assess_file="$case_dir/assessment.json"
    output_json_file="$case_dir/output.json"

    cp "$old_prompt" "$prompt_file"

    log "agent_start case=$id scenario=$rel_file"
    case_start_epoch=$(date +%s)

    set +e
    perl -e 'alarm shift; exec @ARGV' "$AGENT_TIMEOUT_SEC" \
      "$AGENT_BIN" exec \
      -m "$MODEL" \
      --skip-git-repo-check \
      --json \
      -C "$WORKDIR" \
      -o "$output_file" \
      "${AGENT_EXTRA_ARGS[@]}" \
      "$(cat "$prompt_file")" \
      > "$events_file" 2> "$stderr_file"
    exec_code=$?
    set -e

    case_end_epoch=$(date +%s)
    case_duration=$((case_end_epoch - case_start_epoch))
    log "agent_stop case=$id scenario=$rel_file exit_code=$exec_code duration_sec=$case_duration"

    if [[ ! -f "$output_file" ]]; then
      cat > "$output_file" <<'EOF_OUT'
# Subagent Output (Unavailable)

Subagent finished without markdown output. Check `stderr.log` and `events.jsonl`.
EOF_OUT
    fi

    jq -r 'select(.type=="item.completed" and .item.type=="command_execution") | .item.command // empty' "$events_file" > "$commands_file" || true

    extracted_json=""
    json_ok=false
    verdict_actual=""
    if [[ -f "$output_file" ]]; then
      extracted_json=$(extract_last_json_block "$output_file")
    fi

    if [[ -n "$extracted_json" ]] && printf '%s' "$extracted_json" | jq . >/dev/null 2>&1; then
      json_ok=true
      printf '%s' "$extracted_json" | jq '.' > "$output_json_file"
      verdict_actual=$(jq -r --arg k "$ACTUAL_VERDICT_KEY" '.[$k] // empty' "$output_json_file")
    fi

    correctness="fail"
    completeness="fail"
    hallucination="pass"
    pass=false
    notes=()

    if [[ $exec_code -ne 0 ]]; then
      notes+=("subagent_exit_nonzero:$exec_code")
    fi

    if [[ "$json_ok" == "true" ]]; then
      verdict_ok=true
      if [[ -n "$expected_verdict" && "$verdict_actual" != "$expected_verdict" ]]; then
        verdict_ok=false
      fi

      regex_ok=true
      if [[ -n "$expected_regex" ]]; then
        if ! jq -e --arg key "$ACTUAL_LIST_KEY" --arg re "$expected_regex" '(.[$key] // []) | if type=="array" then any(test($re)) else false end' "$output_json_file" >/dev/null; then
          regex_ok=false
        fi
      fi

      if [[ "$verdict_ok" == "true" && "$regex_ok" == "true" ]]; then
        correctness="pass"
      else
        [[ "$verdict_ok" == "false" ]] && notes+=("verdict_mismatch:expected=$expected_verdict,actual=$verdict_actual")
        [[ "$regex_ok" == "false" ]] && notes+=("regex_mismatch:$expected_regex")
      fi

      if [[ -s "$output_file" ]]; then
        if [[ -s "$commands_file" ]] || jq -e '.commands // [] | length > 0' "$output_json_file" >/dev/null 2>&1; then
          completeness="pass"
        else
          notes+=("no_observed_commands")
        fi
      fi

      if [[ -n "$expected_regex" ]]; then
        if ! jq -e --arg key "$ACTUAL_LIST_KEY" --arg re "$expected_regex" '(.[$key] // []) | if type=="array" then any(test($re)) else false end' "$output_json_file" >/dev/null; then
          hallucination="fail"
          notes+=("missing_expected_match_in_$ACTUAL_LIST_KEY")
        fi
      fi
    else
      if [[ "$ALLOW_MISSING_JSON" == "true" ]]; then
        correctness="pass"
      else
        notes+=("no_valid_output_json")
      fi
    fi

    if [[ "$correctness" == "pass" && "$completeness" == "pass" && "$hallucination" == "pass" ]]; then
      pass=true
      score=1.0
      ((passed+=1))
    else
      score=0.0
      ((failed+=1))
    fi
    ((total+=1))

    notes_json=$(printf '%s\n' "${notes[@]-}" | jq -R . | jq -s .)

    jq -n \
      --arg id "$id" \
      --argjson pass "$pass" \
      --argjson score "$score" \
      --arg correctness "$correctness" \
      --arg completeness "$completeness" \
      --arg hallucination "$hallucination" \
      --arg expected_verdict "$expected_verdict" \
      --arg expected_regex "$expected_regex" \
      --arg actual_verdict "$verdict_actual" \
      --arg source_case_file "$rel_file" \
      --argjson notes "$notes_json" \
      '{
        id:$id,
        pass:$pass,
        score:$score,
        checks:{correctness:$correctness,completeness:$completeness,hallucination:$hallucination},
        notes:$notes,
        expected:{verdict:$expected_verdict,regex:$expected_regex},
        actual:{verdict:$actual_verdict},
        source_case_file:$source_case_file,
        evidence:{commands_log:("./cases/"+$id+"/commands.log"),output:("./cases/"+$id+"/output.md")}
      }' > "$assess_file"

    jq -n \
      --arg case_file "$rel_file" \
      --arg id "$id" \
      --argjson pass "$pass" \
      --arg expected_verdict "$expected_verdict" \
      --arg actual_verdict "$verdict_actual" \
      '{case_file:$case_file,id:$id,pass:$pass,expected_verdict:$expected_verdict,actual_verdict:$actual_verdict}' >> "$summary_jsonl"

    log "case_result case=$id scenario=$rel_file pass=$pass expected_verdict=${expected_verdict:-} actual_verdict=${verdict_actual:-} checks=${correctness}/${completeness}/${hallucination}"
  done < "$rerun_manifest"
else
  shopt -s nullglob
  case_files=( $CASES_GLOB )
  shopt -u nullglob

  (( ${#case_files[@]} > 0 )) || { echo "no case files matched: $CASES_GLOB" >&2; exit 2; }

  for case_file in "${case_files[@]}"; do
    rel_file="${case_file#$EVAL_DIR/scenarios/cases/}"
    file_total=0
    file_passed=0
    file_failed=0

    case_count=$(jq 'length' "$case_file")
    log "scenario_start file=$rel_file cases=$case_count"

    for ((i=0; i<case_count; i++)); do
      case_json=$(jq -c ".[$i]" "$case_file")

    id=$(json_get_string "$case_json" "$CASE_ID_KEY")
    [[ -n "$id" ]] || id="${rel_file%.json}__idx_$i"

    question=$(json_get_string "$case_json" "$CASE_QUESTION_KEY")
    expected_verdict=$(json_get_string "$case_json" "$EXPECTED_VERDICT_KEY")
    expected_regex=$(json_get_string "$case_json" "$EXPECTED_REGEX_KEY")

    bean_regex=$(json_get_string "$case_json" "bean_name_regex")
    return_type_regex=$(json_get_string "$case_json" "return_type_regex")
    property_name=$(json_get_string "$case_json" "property_name")
    project_config_dir_rel=$(json_get_string "$case_json" "project_config_dir")
    config_dir_rel=$(json_get_string "$case_json" "config_dir")
    app_name=$(json_get_string "$case_json" "app_name")

    mapfile -t active_profiles_arr < <(jq -r '.active_profiles // [] | .[]' <<<"$case_json")
    runtime_props_json=$(jq -c '.runtime_properties // {}' <<<"$case_json")

    project_config_dir_abs=""
    config_dir_abs=""
    [[ -n "$project_config_dir_rel" ]] && project_config_dir_abs="$EVAL_DIR/scenarios/$project_config_dir_rel"
    [[ -n "$config_dir_rel" ]] && config_dir_abs="$EVAL_DIR/scenarios/$config_dir_rel"

    case_dir="$RUN_DIR/cases/$id"
    mkdir -p "$case_dir"

    prompt_file="$case_dir/prompt.txt"
    output_file="$case_dir/output.md"
    events_file="$case_dir/events.jsonl"
    stderr_file="$case_dir/stderr.log"
    commands_file="$case_dir/commands.log"
    assess_file="$case_dir/assessment.json"
    output_json_file="$case_dir/output.json"

    profiles_joined=""
    if (( ${#active_profiles_arr[@]} > 0 )); then
      profiles_joined=$(printf '%s, ' "${active_profiles_arr[@]}")
      profiles_joined=${profiles_joined%, }
    fi

    cat > "$prompt_file" <<EOF_PROMPT
Ты сабагент для E2E-оценки скилла.

Обязательное поведение:
1) Используй инструкции из SKILL.md:
$SKILL_ROOT/SKILL.md
2) Для этого кейса выполни диагностику по доступному контексту.
3) Выполни наблюдаемые shell-команды, если они нужны для корректного вывода.
4) Верни итог в Markdown.
5) В КОНЦЕ добавь fenced json-блок с полями:
{
  "id": "...",
  "$ACTUAL_VERDICT_KEY": "likely_yes|likely_no|uncertain",
  "$ACTUAL_LIST_KEY": ["..."],
  "reasoning_summary": "...",
  "commands": ["..."]
}

Контекст кейса (known fields):
- id: $id
- question: $question
- regex(bean_name): ${bean_regex:-}
- regex(return_type): ${return_type_regex:-}
- property_name: ${property_name:-}
- project_config_dir: ${project_config_dir_abs:-}
- config_dir: ${config_dir_abs:-}
- app_name: ${app_name:-}
- active_profiles: ${profiles_joined:-}
- runtime_properties: $runtime_props_json
- index: $INDEX_PATH

Контекст кейса (raw json):
$case_json

Ожидания eval (только для ассессмента):
- $EXPECTED_VERDICT_KEY: ${expected_verdict:-}
- $EXPECTED_REGEX_KEY: ${expected_regex:-}
EOF_PROMPT

    log "agent_start case=$id scenario=$rel_file"
    case_start_epoch=$(date +%s)

    set +e
    perl -e 'alarm shift; exec @ARGV' "$AGENT_TIMEOUT_SEC" \
      "$AGENT_BIN" exec \
      -m "$MODEL" \
      --skip-git-repo-check \
      --json \
      -C "$WORKDIR" \
      -o "$output_file" \
      "${AGENT_EXTRA_ARGS[@]}" \
      "$(cat "$prompt_file")" \
      > "$events_file" 2> "$stderr_file"
    exec_code=$?
    set -e

    case_end_epoch=$(date +%s)
    case_duration=$((case_end_epoch - case_start_epoch))
    log "agent_stop case=$id scenario=$rel_file exit_code=$exec_code duration_sec=$case_duration"

    if [[ ! -f "$output_file" ]]; then
      cat > "$output_file" <<'EOF_OUT'
# Subagent Output (Unavailable)

Subagent finished without markdown output. Check `stderr.log` and `events.jsonl`.
EOF_OUT
    fi

    jq -r 'select(.type=="item.completed" and .item.type=="command_execution") | .item.command // empty' "$events_file" > "$commands_file" || true

    extracted_json=""
    json_ok=false
    verdict_actual=""
    if [[ -f "$output_file" ]]; then
      extracted_json=$(extract_last_json_block "$output_file")
    fi

    if [[ -n "$extracted_json" ]] && printf '%s' "$extracted_json" | jq . >/dev/null 2>&1; then
      json_ok=true
      printf '%s' "$extracted_json" | jq '.' > "$output_json_file"
      verdict_actual=$(jq -r --arg k "$ACTUAL_VERDICT_KEY" '.[$k] // empty' "$output_json_file")
    fi

    correctness="fail"
    completeness="fail"
    hallucination="pass"
    pass=false
    notes=()

    if [[ $exec_code -ne 0 ]]; then
      notes+=("subagent_exit_nonzero:$exec_code")
    fi

    if [[ "$json_ok" == "true" ]]; then
      verdict_ok=true
      if [[ -n "$expected_verdict" && "$verdict_actual" != "$expected_verdict" ]]; then
        verdict_ok=false
      fi

      regex_ok=true
      if [[ -n "$expected_regex" ]]; then
        if ! jq -e --arg key "$ACTUAL_LIST_KEY" --arg re "$expected_regex" '(.[$key] // []) | if type=="array" then any(test($re)) else false end' "$output_json_file" >/dev/null; then
          regex_ok=false
        fi
      fi

      if [[ "$verdict_ok" == "true" && "$regex_ok" == "true" ]]; then
        correctness="pass"
      else
        [[ "$verdict_ok" == "false" ]] && notes+=("verdict_mismatch:expected=$expected_verdict,actual=$verdict_actual")
        [[ "$regex_ok" == "false" ]] && notes+=("regex_mismatch:$expected_regex")
      fi

      if [[ -s "$output_file" ]]; then
        if [[ -s "$commands_file" ]] || jq -e '.commands // [] | length > 0' "$output_json_file" >/dev/null 2>&1; then
          completeness="pass"
        else
          notes+=("no_observed_commands")
        fi
      fi

      if [[ -n "$expected_regex" ]]; then
        if ! jq -e --arg key "$ACTUAL_LIST_KEY" --arg re "$expected_regex" '(.[$key] // []) | if type=="array" then any(test($re)) else false end' "$output_json_file" >/dev/null; then
          hallucination="fail"
          notes+=("missing_expected_match_in_$ACTUAL_LIST_KEY")
        fi
      fi
    else
      if [[ "$ALLOW_MISSING_JSON" == "true" ]]; then
        correctness="pass"
      else
        notes+=("no_valid_output_json")
      fi
    fi

    if [[ "$correctness" == "pass" && "$completeness" == "pass" && "$hallucination" == "pass" ]]; then
      pass=true
      score=1.0
      ((passed+=1))
      ((file_passed+=1))
    else
      score=0.0
      ((failed+=1))
      ((file_failed+=1))
    fi
    ((total+=1))
    ((file_total+=1))

    notes_json=$(printf '%s\n' "${notes[@]-}" | jq -R . | jq -s .)

    jq -n \
      --arg id "$id" \
      --argjson pass "$pass" \
      --argjson score "$score" \
      --arg correctness "$correctness" \
      --arg completeness "$completeness" \
      --arg hallucination "$hallucination" \
      --arg expected_verdict "$expected_verdict" \
      --arg expected_regex "$expected_regex" \
      --arg actual_verdict "$verdict_actual" \
      --arg source_case_file "$rel_file" \
      --argjson notes "$notes_json" \
      '{
        id:$id,
        pass:$pass,
        score:$score,
        checks:{correctness:$correctness,completeness:$completeness,hallucination:$hallucination},
        notes:$notes,
        expected:{verdict:$expected_verdict,regex:$expected_regex},
        actual:{verdict:$actual_verdict},
        source_case_file:$source_case_file,
        evidence:{commands_log:("./cases/"+$id+"/commands.log"),output:("./cases/"+$id+"/output.md")}
      }' > "$assess_file"

    jq -n \
      --arg case_file "$rel_file" \
      --arg id "$id" \
      --argjson pass "$pass" \
      --arg expected_verdict "$expected_verdict" \
      --arg actual_verdict "$verdict_actual" \
      '{case_file:$case_file,id:$id,pass:$pass,expected_verdict:$expected_verdict,actual_verdict:$actual_verdict}' >> "$summary_jsonl"

    log "case_result case=$id scenario=$rel_file pass=$pass expected_verdict=${expected_verdict:-} actual_verdict=${verdict_actual:-} checks=${correctness}/${completeness}/${hallucination}"
    done

    log "scenario_end file=$rel_file total=$file_total passed=$file_passed failed=$file_failed"
  done
fi

meta_file="$RUN_DIR/meta.json"
report_file="$RUN_DIR/report.md"

file_summaries=$(jq -s '
  group_by(.case_file)
  | map({
      case_file: .[0].case_file,
      total: length,
      passed: (map(select(.pass==true))|length),
      failed: (map(select(.pass!=true))|length)
    })
' "$summary_jsonl")

jq -n \
  --arg date "$DATE" \
  --arg model "$MODEL" \
  --arg run_id "$RUN_ID" \
  --arg run_dir "$RUN_DIR" \
  --arg skill_declared_version "$SKILL_DECLARED_VERSION" \
  --arg skill_root "$SKILL_ROOT" \
  --arg eval_dir "$EVAL_DIR" \
  --arg index "$INDEX_PATH" \
  --arg cases_glob "$CASES_GLOB" \
  --arg source_run "$RERUN_FAILED_FROM" \
  --arg skill_md_path "$SKILL_MD_PATH" \
  --arg skill_md_sha256 "$SKILL_MD_SHA256" \
  --arg index_sha256 "$INDEX_SHA256" \
  --arg git_commit "$GIT_COMMIT" \
  --arg git_branch "$GIT_BRANCH" \
  --argjson git_dirty "$GIT_DIRTY" \
  --argjson total "$total" \
  --argjson passed "$passed" \
  --argjson failed "$failed" \
  --argjson files "$file_summaries" \
  '{
    date:$date,
    model:$model,
    run_id:$run_id,
    run_dir:$run_dir,
    skill_declared_version:$skill_declared_version,
    skill_root:$skill_root,
    skill_metadata:{
      skill_md_path:$skill_md_path,
      skill_md_sha256:$skill_md_sha256,
      declared_skill_version:$skill_declared_version
    },
    eval_dir:$eval_dir,
    index:$index,
    index_sha256:$index_sha256,
    cases_glob:$cases_glob,
    source_run:$source_run,
    repo:{
      branch:$git_branch,
      commit:$git_commit,
      dirty:$git_dirty
    },
    mode:(if ($source_run|length)>0 then "rerun_failed_only" else "full" end),
    overall:{total:$total,passed:$passed,failed:$failed,pass_rate:(if $total==0 then 0 else (($passed*10000/$total)|floor)/100 end)},
    case_files:$files
  }' > "$meta_file"

